let selectedStory = null;
let currentPage = 0;

function loadLibrary() {
    const libraryEl = document.getElementById("storyLibraryView");
    const readerEl = document.getElementById("storyReaderView");
    const gridEl = document.getElementById("storyGrid");

    if (!libraryEl || !readerEl || !gridEl) return;

    libraryEl.style.display = "block";
    readerEl.style.display = "none";
    gridEl.innerHTML = "";

    stories.forEach(story => {
        const card = document.createElement("div");
        card.className = "subject-card";
        card.style.textAlign = "center";
        card.style.padding = "20px";

        card.innerHTML = `
            <img src="${story.image}" onerror="this.src='${story.fallbackImage}'" alt="${story.title}" class="story-image-card" style="height: 180px;">
            <h3 style="margin: 12px 0 6px 0;">${story.title}</h3>
            <p style="font-size: 0.95rem; color: #666; font-style: italic; margin-bottom: 15px;">Moral: "${story.moral}"</p>
            <button style="width:100%; margin:0;">Read Story</button>
        `;

        card.onclick = () => openStory(story);
        gridEl.appendChild(card);
    });
}

function openStory(story) {
    selectedStory = story;
    currentPage = 0;

    const libraryEl = document.getElementById("storyLibraryView");
    const readerEl = document.getElementById("storyReaderView");

    if (libraryEl && readerEl) {
        libraryEl.style.display = "none";
        readerEl.style.display = "block";
    }

    renderPage();
}

function renderPage() {
    if (!selectedStory) return;

    const page = selectedStory.pages[currentPage];

    document.getElementById("storyTitle").textContent = selectedStory.title;
    document.getElementById("storyText").textContent = page.text;
    const imgEl = document.getElementById("storyIllustration");
    if (imgEl) {
        imgEl.src = page.image;
        imgEl.onerror = () => { imgEl.src = page.fallbackImage; };
    }
    document.getElementById("pageNumberDisplay").textContent = `Page ${currentPage + 1} of ${selectedStory.pages.length}`;
}

function nextPage() {
    if (!selectedStory) return;

    currentPage++;
    if (currentPage >= selectedStory.pages.length) {
        alert(`You finished "${selectedStory.title}"!\n\nMoral: ${selectedStory.moral}\n\n+5 Stars Earned!`);
        
        let profile = (window.YellowPawsStorage && window.YellowPawsStorage.getProfile()) || JSON.parse(localStorage.getItem("yellowPawsProfile")) || {stars: 0};
        const updatedStars = (profile.stars || 0) + 5;
        if (window.YellowPawsStorage) {
            window.YellowPawsStorage.updateProfile({ stars: updatedStars });
        } else {
            profile.stars = updatedStars;
            localStorage.setItem("yellowPawsProfile", JSON.stringify(profile));
        }

        backToLibrary();
        return;
    }
    renderPage();
}

function previousPage() {
    if (currentPage > 0) {
        currentPage--;
        renderPage();
    }
}

function backToLibrary() {
    selectedStory = null;
    currentPage = 0;
    if (window.speechSynthesis) window.speechSynthesis.cancel();
    loadLibrary();
}

function readAloud() {
    if (!selectedStory) return;
    const text = selectedStory.pages[currentPage].text;
    if ('speechSynthesis' in window) {
        window.speechSynthesis.cancel();
        const speech = new SpeechSynthesisUtterance(text);
        speech.rate = 0.95;
        window.speechSynthesis.speak(speech);
    }
}

document.addEventListener("DOMContentLoaded", loadLibrary);
